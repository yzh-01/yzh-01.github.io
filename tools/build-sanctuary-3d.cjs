// Rebuild the checked-in, self-hosted renderer. Normal Hexo builds need no bundler.
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const { execFileSync } = require('node:child_process');
const repo = path.resolve(__dirname, '..');
const toolRoot = process.env.GARDEN_3D_TOOL_ROOT || path.join(os.tmpdir(), 'garden-sanctuary-tools-r180');
const npmRoot = path.join(toolRoot, 'node_modules');
if (!fs.existsSync(path.join(npmRoot, 'esbuild/lib/main.js'))) {
  execFileSync('npm', ['install', '--prefix', toolRoot, '--cache', path.join(toolRoot, '.npm-cache'),
    '--no-audit', '--no-fund', '--save-exact', 'three@0.180.0', 'esbuild@0.25.10'], {stdio:'inherit'});
}
const esbuild = require(path.join(npmRoot, 'esbuild'));
const three = path.join(npmRoot, 'three');
const vendorDir = path.join(repo, 'themes/garden/source/js/vendor');
const bundlePath = path.join(vendorDir, 'norse-engine.mjs');
fs.mkdirSync(vendorDir, {recursive:true});
esbuild.buildSync({entryPoints:[path.join(__dirname, 'norse-engine.entry.mjs')],
  outfile:bundlePath, bundle:true, minify:true,
  format:'esm', target:'es2020', legalComments:'inline',
  alias:{three, 'three/addons':path.join(three, 'examples/jsm')},
  banner:{js:'/* Three.js 0.180.0 · MIT · see three.LICENSE.txt. Generated by tools/build-sanctuary-3d.cjs. */'}});
// Shader template literals retain line endings; trim their trailing spaces so
// the generated bundle also passes the repository's whitespace check.
fs.writeFileSync(bundlePath, fs.readFileSync(bundlePath, 'utf8').replace(/[ \t]+$/gm, ''));
fs.copyFileSync(path.join(three, 'LICENSE'), path.join(vendorDir, 'three.LICENSE.txt'));
console.log('Self-hosted Three.js r180 renderer rebuilt.');
